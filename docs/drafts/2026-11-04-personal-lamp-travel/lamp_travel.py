"""Extract personal travel allowlists from unmodified CUSA03173 1.09 scripts.

Only numeric talk IDs and destinations are emitted; no game assets are copied.
"""
import argparse
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bbfiles
import esd
from emevd import Emevd

HEADER = Path(__file__).resolve().parents[2] / 'emulator/src/core/bbsc_lamp_travel_data.h'


def generate(game):
    talks, returns = [], []
    for path in sorted((game / 'script/talk').glob('*.talkesdbnd.dcx')):
        if path.name.startswith(('m29_', 'm10_')):
            continue
        for name, (_, data) in bbfiles.read_bnd4(bbfiles.read_dcx(path)).items():
            if not name.startswith('t') or not name.endswith('.esd'):
                continue
            talk = int(name[1:-4])
            if talk // 10000 == 21 and talk not in (210000, 210001, 210002, 210003, 210721):
                continue
            script = esd.Esd(data)
            commands = [command for group in script.groups.values()
                        for state in group['states'].values() for command in state['entry']]
            # Ground lamps request native lamp travel; headstones request event 12107000.
            marker = '72100000' if talk // 10000 == 21 else '70000200'
            if any(b == 1 and i == 11 and a and marker in a[0][0]
                   for b, i, a in commands):
                talks.append(talk)
    dream = Emevd(game / 'event/m21_00_00_00.emevd.dcx')
    for event, instructions in dream.events:
        if event != 0:
            continue
        for bank, index, args in instructions:
            if bank == 2000 and index == 0 and len(args) == 20:
                slot, template, flag, entity, point = struct.unpack('<5i', args)
                if template == 12107000:
                    returns.append((flag, point))
    assert len(returns) == 44 and len(set(talks)) == len(talks)
    out = ['// Generated by tools/gamedata/lamp_travel.py; numeric CUSA03173 1.09 rules.',
           '#pragma once', '#include <array>', '#include <cstdint>',
           'namespace Core::Bloodborne::LampTravel {',
           f'inline constexpr std::array<std::uint32_t, {len(talks)}> Talks{{']
    out += [f'    {talk},' for talk in sorted(talks)]
    out += ['};', 'struct Return { std::uint32_t flag; std::int32_t point; };',
            f'inline constexpr std::array<Return, {len(returns)}> Returns{{{{']
    out += [f'    {{{flag}, {point}}},' for flag, point in sorted(returns)]
    out += ['}};', '} // namespace Core::Bloodborne::LampTravel', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--game', type=Path, required=True, help='Read-only dvdroot_ps4')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.game)
    if args.check:
        assert HEADER.read_text(encoding='utf-8') == result, 'Regenerate lamp travel rules'
        print('Lamp travel rules match original game scripts')
    else:
        HEADER.write_text(result, encoding='utf-8')
