"""Punctuation and original Russian text for co-op screen notices.

Keep the original bell/resonance wording where seamless co-op has the same meaning.
Covenant warnings are excluded. Menu help and item descriptions are not notices.
"""
import re


def notice_text(text):
    """Drop a single sentence's full stop; preserve ellipses and multiple sentences."""
    if not text.endswith('.') or text.endswith('...'):
        return text
    body = text[:-1]
    if re.search(r'[.!?](?:\s|$)', body):
        return text
    return body


